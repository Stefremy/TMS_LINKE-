"""Rebuild the all-day pickup cutoff table from the supplied PDF (requires pypdf)."""
from pathlib import Path
from pypdf import PdfReader
import hashlib
import json
import re

root = Path(__file__).resolve().parent.parent
source = root / 'docs/Horas+de+Corte_Recolhas_Pedido.pdf'
reader = PdfReader(source)
rows = {}
for page_number, page in enumerate(reader.pages, 1):
    for line in page.extract_text().splitlines():
        if not re.match(r'^\d{4}\s', line):
            continue
        match = re.fullmatch(r'(\d{4})\s+(.+?)\s+D-1:\s*(\d\d:\d\d)\s+D-1:\s*(\d\d:\d\d)\s+(\d\d:\d\d|N\s*/\s*A)\s+(\d\d:\d\d|N\s*/\s*A)\s+(\d\d:\d\d|N\s*/\s*A)\s+(\d\d:\d\d|N\s*/\s*A)\s*', line)
        if not match:
            raise ValueError(f'Unparsed row on PDF page {page_number}: {line}')
        cp, locality, *times = match.groups()
        if cp in rows:
            raise ValueError(f'Duplicate postal prefix: {cp}')
        cutoff = times[-1]  # Last column: Recolhas até às 19h no próprio dia.
        if cutoff not in ('13:00', '16:00'):
            raise ValueError(f'Unexpected all-day cutoff for {cp}: {cutoff}')
        rows[cp] = [locality, cutoff, page_number]
if len(reader.pages) != 13 or len(rows) != 506:
    raise ValueError('Source changed; review page/row counts before importing.')
header = '// Generated by scripts/import-ctt-pickup-cutoffs.py; do not edit by hand.\n'
header += '// Source: docs/Horas+de+Corte_Recolhas_Pedido.pdf, final column (pickup until 19:00).\n'
header += '// Source SHA-256: ' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n'
header += 'export const CTT_PICKUP_CUTOFFS: Record<string, readonly [locality: string, allDayCutoff: string, pdfPage: number]> = '
(root / 'lib/data/ctt-pickup-cutoffs.ts').write_text(header + '{\n' + ',\n'.join('  ' + json.dumps(cp) + ': ' + json.dumps(row, ensure_ascii=False) for cp, row in rows.items()) + '\n}\n')
print(f'Imported {len(rows)} postal prefixes from {len(reader.pages)} pages.')
